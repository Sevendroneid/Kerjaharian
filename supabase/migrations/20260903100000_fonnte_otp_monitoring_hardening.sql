create or replace function public.fonnte_monitor_snapshot()
returns jsonb language sql security definer set search_path = public as $$
  select jsonb_build_object('status',c.last_status,'reason',c.last_reason,'device',c.device,'last_event_at',c.last_event_at,'last_health_check_at',c.last_health_check_at,'consecutive_failures',c.consecutive_failures)
  from public.fonnte_monitor_config c where c.id=true;
$$;
revoke all on function public.fonnte_monitor_snapshot() from public, anon;
grant execute on function public.fonnte_monitor_snapshot() to authenticated;
create or replace function public.consume_fonnte_otp(p_phone text, p_code_hash text)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_id uuid;
begin
  select id into v_id from public.otp_codes where phone=p_phone and used=false and expired_at>now() and (code_hash=p_code_hash or (code_hash is null and code=p_code_hash)) order by created_at desc limit 1 for update;
  if v_id is null then
    update public.otp_codes set attempts=attempts+1 where phone=p_phone and used=false and expired_at>now();
    return false;
  end if;
  update public.otp_codes set used=true, attempts=attempts+1 where id=v_id;
  return true;
end; $$;
revoke all on function public.consume_fonnte_otp(text,text) from public, anon, authenticated;
create or replace function public.record_fonnte_health_failure(p_reason text)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.fonnte_monitor_config set last_status='unknown', last_reason=left(coalesce(p_reason,'unknown'),500), last_health_check_at=now(), consecutive_failures=consecutive_failures+1, updated_at=now() where id=true;
  insert into public.fonnte_device_status(device,status,reason,source,event_at,checked_at,raw) values ('unknown','unknown',left(coalesce(p_reason,'unknown'),500),'healthcheck',now(),now(),jsonb_build_object('error',p_reason));
end; $$;
revoke all on function public.record_fonnte_health_failure(text) from public, anon, authenticated;
