create table if not exists public.fonnte_device_status (
  id bigint generated by default as identity primary key,
  device text not null,
  status text not null check (status in ('connect','disconnect','unknown')),
  reason text,
  source text not null default 'webhook' check (source in ('webhook','healthcheck')),
  event_at timestamptz not null default now(),
  checked_at timestamptz not null default now(),
  raw jsonb,
  created_at timestamptz not null default now()
);
create index if not exists fonnte_device_status_device_event_idx on public.fonnte_device_status(device,event_at desc);
create table if not exists public.fonnte_monitor_config (
  id boolean primary key default true check (id),
  webhook_secret text not null default encode(gen_random_bytes(32),'hex'),
  health_secret text not null default encode(gen_random_bytes(32),'hex'),
  device text,
  last_status text not null default 'unknown' check (last_status in ('connect','disconnect','unknown')),
  last_reason text,
  last_event_at timestamptz,
  last_health_check_at timestamptz,
  consecutive_failures integer not null default 0,
  updated_at timestamptz not null default now()
);
insert into public.fonnte_monitor_config (id) values (true) on conflict (id) do nothing;
